"""
Builds src/data/fbs/history.ts from the program history research in docs/research/history_*.json,
after validating it against the team profiles. Run from the repo root:  python scripts/build_history.py
History runs through the 2025 season; the game's first season is 2026. Display only: nothing in the
sim reads it (see docs/PROGRAM.md).
"""
import json, glob, os, re, sys
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SP = os.path.join(REPO, 'docs', 'research')
LAST = 2025
YEARS = list(range(LAST - 4, LAST + 1))

profiles = []
for f in sorted(glob.glob(os.path.join(SP, 'profiles_*.json'))):
    profiles += json.load(open(f, encoding='utf-8'))
ids = {t['id'] for t in profiles}

teams = []
for f in sorted(glob.glob(os.path.join(SP, 'history_*.json'))):
    teams += json.load(open(f, encoding='utf-8'))
seen = [t['id'] for t in teams]
assert len(seen) == len(set(seen)), [i for i in seen if seen.count(i) > 1]
problems = [f'unknown id: {i}' for i in seen if i not in ids]
problems += [f'missing: {i}' for i in sorted(ids - set(seen))]

def years(xs, lo=1869):
    xs = sorted({int(y) for y in xs or []})
    assert all(lo <= y <= LAST for y in xs), xs
    return xs

def count(x):
    return max(0, int(x or 0))

out = {}
for t in teams:
    i = t['id']
    if i not in ids: continue
    try:
        b = t.get('bowls') or {}
        a = t.get('allTime') or {}
        rec = {r['year']: r for r in t.get('recent') or []}
        recent = []
        for y in YEARS:
            r = rec.get(y)
            if not r:
                problems.append(f'{i}: no {y} season')
                continue
            row = {'year': y, 'conf': str(r.get('conf') or 'Independent'), 'w': count(r['w']), 'l': count(r['l']),
                   'cw': count(r.get('cw')), 'cl': count(r.get('cl'))}
            if r.get('ap'):
                row['ap'] = int(r['ap'])
                assert 1 <= row['ap'] <= 25, (i, y, r['ap'])
            if r.get('post'):
                row['post'] = str(r['post']).upper()[:28]
            recent.append(row)
        h = {
            'natTitles': years(t.get('natTitles')),
            'confTitles': count(t.get('confTitles')),
            'lastConf': int(t['lastConf']) if t.get('lastConf') else None,
            'playoffs': years(t.get('playoffs'), 2014),
            'bowls': {'apps': count(b.get('apps')), 'w': count(b.get('w')), 'l': count(b.get('l')), 't': count(b.get('t')),
                      'last': int(b['last']) if b.get('last') else None},
            'heisman': sorted([{'name': str(x['name']), 'year': int(x['year'])} for x in t.get('heisman') or []], key=lambda x: x['year']),
            'allTime': {'w': count(a.get('w')), 'l': count(a.get('l')), 't': count(a.get('t'))},
            'coachSince': int(t.get('coachSince') or LAST + 1),
            'recent': recent,
        }
        if t.get('fcsTitles'): h['fcsTitles'] = years(t['fcsTitles'])
        bw = h['bowls']
        if bw['w'] + bw['l'] + bw['t'] != bw['apps']:
            problems.append(f"{i}: bowl W-L-T {bw['w']}-{bw['l']}-{bw['t']} != {bw['apps']} apps")
        if not 1990 <= h['coachSince'] <= LAST + 1:
            problems.append(f"{i}: coachSince {h['coachSince']}")
        out[i] = h
    except (AssertionError, KeyError, TypeError, ValueError) as e:
        problems.append(f'{i}: bad record {e!r}')

for p in problems: print('WARN', p, file=sys.stderr)

lines = [
    '// Generated by scripts/build_history.py from docs/research/history_*.json. Do not edit by hand.',
    "import type { ProgramHistory } from './programHistory';",
    '',
    '/** Real program history through the 2025 season, by team id. Display only (docs/PROGRAM.md). */',
    'export const TEAM_HISTORY: Record<string, ProgramHistory> = {',
]
for i in sorted(out):
    lines.append(f'  {i}: {json.dumps(out[i], separators=(",", ":"))},')
lines.append('};')
lines.append('')
open(os.path.join(REPO, 'src/data/fbs/history.ts'), 'w', encoding='utf-8').write('\n'.join(lines))
print(f'{len(out)} teams, {len(problems)} warnings')
