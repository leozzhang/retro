"""Route mix, same-side route pairs, and route results by coverage, for building the playbook.

Needs analysis/out/route_metrics.csv from route_metrics.py.

    python analysis/concepts.py nfl-big-data-bowl-2027
"""
from __future__ import annotations

import numpy as np
import pandas as pd

from nfldata import CENTER_Y, OUT, data_dir_arg, load_player_play, md_table

# Our concepts (src/data/concepts.ts) as (outer route, inner route) in NFL labels.
OUR_PAIRS = {
    "verts": ("GO", "GO"), "smash": ("HITCH", "CORNER"), "slant-flat": ("SLANT", "FLAT"),
    "slant-drag": ("SLANT", "CROSS"), "mesh": ("CORNER", "CROSS"), "dagger": ("IN", "GO"),
    "curl-flat": ("HITCH", "FLAT"), "post-curl": ("POST", "HITCH"), "go-out": ("GO", "OUT"),
    "post-drag": ("POST", "CROSS"), "in-go": ("IN", "GO"), "comeback-seam": ("HITCH", "GO"),
}


def down_bucket(r) -> str:
    if r.down == 3 or r.down == 4:
        return f"3rd/4th & {'short (1-3)' if r.yards_to_go <= 3 else 'medium (4-7)' if r.yards_to_go <= 7 else 'long (8+)'}"
    return "1st down" if r.down == 1 else "2nd down"


def main():
    pp = load_player_play(data_dir_arg())
    m = pd.read_csv(OUT / "route_metrics.csv")
    m = m.merge(pp[["game_id", "play_id", "nfl_id", "down", "yards_to_go", "rec_yards",
                    "separation_at_pass_forward", "team_coverage_man_zone"]])
    m["situation"] = [down_bucket(r) for r in m.itertuples()]
    out = ["# Route concepts and results (NFL 2023-25)\n",
           "Generated by `analysis/concepts.py`. Only drafted 2023-25 players are tracked, so this is a "
           "sample of routes, not every route on a play.\n"]

    # 1. Route mix
    mix = pd.crosstab([m.formation, m.pos], m.route, normalize="index").mul(100).round(1)
    mix.insert(0, "n", m.groupby(["formation", "pos"]).size())
    mix = mix[mix.n >= 100]
    out += ["## Route mix by formation and position (% of routes)\n", md_table(mix)]
    sit = pd.crosstab(m.situation, m.route, normalize="index").mul(100).round(1)
    sit.insert(0, "n", m.groupby("situation").size())
    out += ["\n## Route mix by situation (% of routes)\n", md_table(sit)]

    # 2. Same-side pairs: order the tracked receivers on a side from the sideline in
    s = m[~m.ambiguous_side & (m.motion != True)].copy()
    ref = s.ball_y.fillna(CENTER_Y)
    s["side"] = np.where(s.snap_y < ref, "lo", "hi")
    s = s.sort_values("sideline_dist")
    pairs = []
    for _, g in s.groupby(["game_id", "play_id", "side"]):
        if len(g) >= 2:
            r, p = g.route.tolist(), g.pos.tolist()
            for i in range(len(g) - 1):
                pairs.append(dict(outer=r[i], inner=r[i + 1], outer_pos=p[i], inner_pos=p[i + 1],
                                  formation=g.formation.iloc[0], gap=g.sideline_dist.iloc[i + 1] - g.sideline_dist.iloc[i]))
    pr = pd.DataFrame(pairs)
    top = pr.groupby(["outer", "inner"]).size().sort_values(ascending=False).rename("n").to_frame()
    top["share %"] = (top.n / len(pr) * 100).round(1)
    top["rank"] = np.arange(1, len(top) + 1)
    ours = pd.DataFrame([(k, *v) for k, v in OUR_PAIRS.items()], columns=["concept", "outer", "inner"])
    ours = ours.join(top, on=["outer", "inner"])
    out += ["\n## Same-side route pairs (outer receiver, next receiver inside)\n",
            f"{len(pr)} adjacent pairs from plays with 2+ tracked receivers on one side. A receiver between "
            "them may be untracked, so treat these as outer/inner, not exact #1/#2.\n",
            md_table(top.head(30)),
            "\n### Our concepts' #1/#2 pairs in that ranking\n",
            md_table(ours.set_index("concept"))]
    pos_pairs = pr.groupby(["outer_pos", "inner_pos", "outer", "inner"]).size().rename("n")
    pos_pairs = pos_pairs.sort_values(ascending=False).head(25).to_frame()
    out += ["\n### Top pairs with positions\n", md_table(pos_pairs)]

    # 3. Results when targeted, by coverage
    t = m[m.target == True]
    t = t.assign(comp=t.pass_result == "C", intc=t.pass_result == "IN")

    def res(g):
        return pd.Series(dict(targets=len(g), comp_pct=g.comp.mean() * 100, int_pct=g.intc.mean() * 100,
                              yds_per_target=g.rec_yards.fillna(0).mean(),
                              sep_p50=g.separation_at_pass_forward.median()))

    by_route = t.groupby("route").apply(res).round(1)
    mz = t.groupby(["route", "team_coverage_man_zone"]).apply(res).round(1)
    cov = t[t.coverage.isin(["COVER_0_MAN", "COVER_1_MAN", "COVER_2_ZONE", "COVER_3_ZONE", "COVER_4_ZONE", "COVER_6_ZONE"])]
    ypt = cov.pivot_table(index="route", columns="coverage", values="rec_yards", aggfunc=lambda v: v.fillna(0).mean()).round(1)
    cnt = cov.pivot_table(index="route", columns="coverage", values="game_id", aggfunc="size")
    ypt = ypt.where(cnt >= 30)
    out += ["\n## Results when targeted\n", md_table(by_route),
            "\n### Man vs zone\n", md_table(mz[mz.targets >= 30]),
            "\n### Yards per target by coverage (cells with 30+ targets)\n", md_table(ypt)]

    (OUT / "concepts.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(md_table(top.head(20)))
    print(md_table(ours.set_index("concept")))
    print(md_table(by_route))
    print(md_table(ypt))


if __name__ == "__main__":
    main()
