"""Receiver alignments at the snap, by formation and receiver alignment.

Covers route runners only (blockers aren't in the route cache). Needs
analysis/out/route_metrics.csv from route_metrics.py.

    python analysis/splits.py nfl-big-data-bowl-2027
"""
from __future__ import annotations

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from nfldata import (CENTER_Y, FIELD_W, NCAA_HASH, NFL_HASH, OL, OUT, ball_y, data_dir_arg, load_player_play,
                     load_routes_cache, md_table, pct_table, snap_frames)

POS = ["WR", "SLOT_WR", "TE"]
FORMS = ["SHOTGUN", "SINGLEBACK", "EMPTY", "PISTOL", "I_FORM"]
ALIGNS = ["2x2", "3x1", "2x1", "3x2"]

# Game alignments from src/data/plays.ts (sideline distance for 'abs' slots, ball split for 'rel').
GAME = [
    ("Gun Doubles / Pistol / Singleback", "X (WR)", "sideline 6.0, depth -0.6"),
    ("Gun Doubles / Pistol / Singleback", "Z (WR)", "sideline 6.0, depth -1.5"),
    ("Gun Doubles / Pistol / Singleback", "SL (slot)", "sideline 14.0, depth -1.5"),
    ("all", "TE", "ball split 3.8, depth -0.8"),
    ("Gun Trips Rt", "SL (slot)", "sideline 13.8, depth -1.5"),
    ("Gun Empty", "TE slot (#3)", "sideline 20.3, depth -1.5"),
]


def main():
    m = pd.read_csv(OUT / "route_metrics.csv")
    m = m[m.pos.isin(POS)]
    still = m[m.motion != True]
    cols = ["sideline_dist", "align_depth"]

    a = pct_table(still[still.formation.isin(FORMS) & still.alignment.isin(ALIGNS)],
                  ["formation", "alignment", "pos"], cols, qs=(0.25, 0.5, 0.75))
    a = a[a.n >= 30]

    # Ball known (center tracked): split from the ball, boundary vs field side.
    b = still[still.ball_y_known].copy()
    b["ball_spot"] = np.where((b.ball_y - CENTER_Y).abs() < 2, "middle", "hash")
    near_sideline_side = np.sign(CENTER_Y - b.ball_y)  # -1: ball is near the y=0 sideline
    rec_side = np.sign(b.snap_y - b.ball_y)
    b["side"] = np.where(b.ball_spot == "middle", "middle",
                         np.where(rec_side == -near_sideline_side, "boundary", "field"))
    bt = pct_table(b, ["pos", "ball_spot", "side"], ["split_from_ball", "sideline_dist", "align_depth"],
                   qs=(0.25, 0.5, 0.75))
    ballspot = b.drop_duplicates(["game_id", "play_id"]).ball_y
    hash_dist = np.minimum(ballspot, FIELD_W - ballspot)

    motion = m.groupby("pos").motion.apply(lambda s: (s == True).mean()).round(3)
    ol = ol_splits()

    text = [
        "# Receiver splits at the snap (NFL route runners)\n",
        "Generated by `analysis/splits.py`. Players in motion at the snap are left out. "
        "Distances are body positions in yd. Depth is relative to the LOS (the front of the ball); "
        "linemen sit at about -0.7 (C) to -1.4 (T).\n",
        f"Hashes: NFL {NFL_HASH} yd from the sideline, college {NCAA_HASH}. For outside WRs the sideline distance "
        "transfers to college. Slot splits are tied to the ball, so they'll sit about 3.6 yd closer to the "
        "sideline on a college hash.\n",
        f"Ball spot on plays with a tracked center (n={len(ballspot)}): distance from the nearer sideline "
        f"p25/p50/p75 = {hash_dist.quantile(.25):.1f} / {hash_dist.median():.1f} / {hash_dist.quantile(.75):.1f}.\n",
        "## By formation, receiver alignment and position\n",
        md_table(a),
        "\n## Split from the ball, boundary vs field (plays with a tracked center)\n",
        md_table(bt[bt.n >= 20]),
        "\n## Offensive line splits from the ball (plays with a tracked center)\n",
        "Game: G 1.2, T 2.4 from the ball, at depth -0.6 (C -0.5).\n",
        md_table(ol),
        "\n## Share of route runners in motion at the snap\n",
        md_table(motion.to_frame("motion share")),
        "\n## Game alignments for comparison (`src/data/plays.ts`)\n",
        md_table(pd.DataFrame(GAME, columns=["formation", "player", "alignment"]), index=False),
    ]
    (OUT / "splits.md").write_text("\n".join(text) + "\n", encoding="utf-8")
    print(md_table(a.loc[["SHOTGUN"]]))
    print(md_table(bt[bt.n >= 20]))
    print(motion)
    plot(still, b)


def ol_splits() -> pd.DataFrame:
    pp = load_player_play(data_dir_arg())
    snap = snap_frames(load_routes_cache())
    by = ball_y(snap, pp)
    o = snap.merge(pp[pp.on_offense & pp.lined_up_position.isin(OL)][["game_id", "play_id", "nfl_id", "lined_up_position", "los_x"]])
    o = o.join(by, on=["game_id", "play_id"]).dropna(subset=["ball_y"])
    o["split_from_ball"] = (o.y - o.ball_y).abs()
    o["align_depth"] = o.x - o.los_x
    return pct_table(o, "lined_up_position", ["split_from_ball", "align_depth"], qs=(0.25, 0.5, 0.75))


def plot(still, b):
    fig, axes = plt.subplots(1, 2, figsize=(15, 5))
    colors = {"WR": "#1f77b4", "SLOT_WR": "#ff7f0e", "TE": "#2ca02c"}
    for pos, c in colors.items():
        axes[0].hist(still[still.pos == pos].sideline_dist, bins=np.arange(0, 27, 0.5), alpha=0.5,
                     color=c, label=pos, density=True)
        v = b[(b.pos == pos) & (b.side != "middle")]
        for side, ls in (("boundary", "-"), ("field", "--")):
            h, e = np.histogram(v[v.side == side].split_from_ball, bins=np.arange(0, 25, 0.5), density=True)
            axes[1].step(e[:-1], h, where="post", color=c, ls=ls, label=f"{pos} {side}")
    for x, lbl in ((6, "game X/Z"), (14, "game slot")):
        axes[0].axvline(x, color="k", lw=0.8, ls=":")
        axes[0].text(x + 0.2, axes[0].get_ylim()[1] * 0.9, lbl, fontsize=8)
    axes[0].axvline(NFL_HASH, color="#999", lw=0.8)
    axes[0].set_title("Sideline distance at the snap (grey line = NFL hash)")
    axes[1].set_title("Split from the ball, ball on a hash (solid boundary, dashed field)")
    for ax in axes:
        ax.set_xlabel("yd")
        ax.legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(OUT / "splits.png", dpi=90)


if __name__ == "__main__":
    main()
